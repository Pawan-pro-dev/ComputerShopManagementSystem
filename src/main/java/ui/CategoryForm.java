    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String name = txtCategoryName.getText().trim();
        String description = txtDescription.getText().trim();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter category name!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Category category = new Category(name, description);
            boolean isAdded = categoryDAO.addCategory(category);

            if (isAdded) {
                JOptionPane.showMessageDialog(this, "Category added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                clearFields();
                loadAllCategories();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to add category!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txtCategoryId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a category from the table!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int id = Integer.parseInt(txtCategoryId.getText().trim());
            String name = txtCategoryName.getText().trim();
            String description = txtDescription.getText().trim();

            if (name.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter category name!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Category category = new Category(id, name, description);
            boolean isUpdated = categoryDAO.updateCategory(category);

            if (isUpdated) {
                JOptionPane.showMessageDialog(this, "Category updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                clearFields();
                loadAllCategories();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update category!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txtCategoryId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a category from the table!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this category?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(txtCategoryId.getText().trim());
                boolean isDeleted = categoryDAO.deleteCategory(id);

                if (isDeleted) {
                    JOptionPane.showMessageDialog(this, "Category deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    clearFields();
                    loadAllCategories();
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to delete category!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblCategoryMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCategoryMouseClicked
        int selectedRow = tblCategory.getSelectedRow();
        DefaultTableModel model = (DefaultTableModel) tblCategory.getModel();

        txtCategoryId.setText(model.getValueAt(selectedRow, 0).toString());
        txtCategoryName.setText(model.getValueAt(selectedRow, 1) != null ? model.getValueAt(selectedRow, 1).toString() : "");
        txtDescription.setText(model.getValueAt(selectedRow, 2) != null ? model.getValueAt(selectedRow, 2).toString() : "");
    }//GEN-LAST:event_tblCategoryMouseClicked

