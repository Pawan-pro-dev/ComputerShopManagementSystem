    private void loadAllSuppliers() {
        try {
            DefaultTableModel model = (DefaultTableModel) tblSupplier.getModel();
            model.setRowCount(0);

            List<Supplier> list = supplierDAO.getAllSuppliers();
            for (Supplier s : list) {
                model.addRow(new Object[]{
                    s.getSupplierId(),
                    s.getName(),
                    s.getCompanyName(),
                    s.getPhone(),
                    s.getEmail(),
                    s.getAddress()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading suppliers: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
