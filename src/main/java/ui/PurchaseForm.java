    private void loadSuppliers() {
        try {
            cmbSupplier.removeAllItems();
            supplierList = supplierDAO.getAllSuppliers(); 
            
            if (supplierList != null) {
                for (Supplier s : supplierList) {
                    cmbSupplier.addItem(s.getName());
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading suppliers: " + e.getMessage());
        }
    }
    
    private void loadProducts() {
        try {
            cmbProduct.removeAllItems();
            productList = productDAO.getAllProducts();
            if (productList != null) {
                for (Product p : productList) {
                    cmbProduct.addItem(p.getProductName());
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading products: " + e.getMessage());
        }
        
    }
        
    private void calculateGrandTotal() {
        grandTotal = 0.0;
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            Object val = model.getValueAt(i, 4);
            if (val != null) {
                try {
                    grandTotal += Double.parseDouble(val.toString());
                } catch (NumberFormatException e) {
                    // Ignore invalid double parse
                }
            }
        }
        txtGrandTotal.setText(String.format("%.2f", grandTotal));
    }

