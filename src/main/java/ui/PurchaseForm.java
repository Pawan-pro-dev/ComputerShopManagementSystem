    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        if (cmbProduct.getSelectedItem() == null || productList == null) return;

        String qtyStr = txtQty.getText().trim();
        String priceStr = txtUnitPrice.getText().trim();

        if (qtyStr.isEmpty() || priceStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Quantity and Unit Price!", "Validation", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int qty = Integer.parseInt(qtyStr);
            double unitPrice = Double.parseDouble(priceStr);

            if (qty <= 0 || unitPrice <= 0) {
                JOptionPane.showMessageDialog(this, "Quantity and Unit Price must be greater than zero!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int selectedIndex = cmbProduct.getSelectedIndex();
            if (selectedIndex == -1 || selectedIndex >= productList.size()) return;

            Product selectedProduct = productList.get(selectedIndex);
            int productId = selectedProduct.getProductId();
            String selectedProductName = selectedProduct.getProductName();

            DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
            boolean isItemExists = false;

            for (int i = 0; i < model.getRowCount(); i++) {
                int existingProdId = Integer.parseInt(model.getValueAt(i, 0).toString());
                double existingPrice = Double.parseDouble(model.getValueAt(i, 2).toString());

                if (existingProdId == productId && existingPrice == unitPrice) {
                    int existingQty = Integer.parseInt(model.getValueAt(i, 3).toString());
                    int newQty = existingQty + qty;
                    double newSubtotal = newQty * unitPrice;

                    model.setValueAt(newQty, i, 3);
                    model.setValueAt(newSubtotal, i, 4);

                    isItemExists = true;
                    break;
                }
            }

            if (!isItemExists) {
                double subtotal = qty * unitPrice;
                model.addRow(new Object[]{
                    productId,
                    selectedProductName,
                    unitPrice,
                    qty,
                    subtotal
                });
            }
            
            calculateGrandTotal();
            txtQty.setText("");
            txtUnitPrice.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for Quantity and Price!", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddToCartActionPerformed

    private void btnRemoveItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveItemActionPerformed
        int selectedRow = tblCart.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
            model.removeRow(selectedRow);
            calculateGrandTotal();
        } else {
            JOptionPane.showMessageDialog(this, "Please select an item from cart to remove!", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnRemoveItemActionPerformed

    private void btnSavePurchaseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSavePurchaseActionPerformed
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty! Please add items to cart before saving.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (cmbSupplier.getSelectedItem() == null || supplierList == null) {
            JOptionPane.showMessageDialog(this, "Please select a supplier!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int selectedSupplierIndex = cmbSupplier.getSelectedIndex();
            if (selectedSupplierIndex == -1 || selectedSupplierIndex >= supplierList.size()) return;

            int supplierId = supplierList.get(selectedSupplierIndex).getSupplierId(); 
            
            int userId = 1; 

            String paymentMethod = cmbPaymentMethod.getSelectedItem().toString();
            String paymentStatus = cmbPaymentStatus.getSelectedItem().toString();

            Purchase purchase = new Purchase(supplierId, userId, grandTotal, paymentMethod, paymentStatus);
            List<PurchaseItem> items = new ArrayList<>();

            for (int i = 0; i < model.getRowCount(); i++) {
                int pId = Integer.parseInt(model.getValueAt(i, 0).toString());
                double price = Double.parseDouble(model.getValueAt(i, 2).toString());
                int qty = Integer.parseInt(model.getValueAt(i, 3).toString());
                double subtotal = Double.parseDouble(model.getValueAt(i, 4).toString());

                PurchaseItem item = new PurchaseItem(pId, qty, price, subtotal);
                items.add(item);
            }

            boolean success = purchaseDAO.savePurchaseTransaction(purchase, items);

            if (success) {
                JOptionPane.showMessageDialog(this, "Purchase saved successfully and stock updated!", "Success", JOptionPane.INFORMATION_MESSAGE);
                model.setRowCount(0);
                calculateGrandTotal();
                txtQty.setText("");
                txtUnitPrice.setText("");
                loadProducts();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save purchase transaction!", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving purchase: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSavePurchaseActionPerformed

