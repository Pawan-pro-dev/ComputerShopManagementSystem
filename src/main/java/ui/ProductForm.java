    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String name = txtProductName.getText().trim();
        String brand = txtBrand.getText().trim();
        String modelStr = txtModel.getText().trim();
        String buyingPriceStr = txtBuyingPrice.getText().trim();
        String sellingPriceStr = txtSellingPrice.getText().trim();
        String stockStr = txtStockQuantity.getText().trim();

        if (name.isEmpty() || buyingPriceStr.isEmpty() || sellingPriceStr.isEmpty() || stockStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all required fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double buyingPrice = Double.parseDouble(buyingPriceStr);
            double sellingPrice = Double.parseDouble(sellingPriceStr);
            int stock = Integer.parseInt(stockStr);

            if (buyingPrice < 0 || sellingPrice < 0 || stock < 0) {
                JOptionPane.showMessageDialog(this, "Prices and stock quantity cannot be negative!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String selectedCategoryName = cmbCategory.getSelectedItem() != null ? cmbCategory.getSelectedItem().toString() : "";
            int categoryId = -1;
            List<Category> categories = categoryDAO.getAllCategories();
            for (Category cat : categories) {
                if (cat.getCategoryName().equalsIgnoreCase(selectedCategoryName)) {
                    categoryId = cat.getCategoryId();
                    break;
                }
            }

            if (categoryId == -1) {
                JOptionPane.showMessageDialog(this, "Please select a valid Category!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Product product = new Product(categoryId, name, brand, modelStr, buyingPrice, sellingPrice, stock);
            boolean isAdded = productDAO.addProduct(product);

            if (isAdded) {
                JOptionPane.showMessageDialog(this, "Product added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                clearFields();
                loadAllProducts();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to add product!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for prices and quantity!", "Input Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txtProductId.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a product from the table to update!", "Warning", JOptionPane.WARNING_MESSAGE);
        return;
        }

        String name = txtProductName.getText().trim();
        String buyingPriceStr = txtBuyingPrice.getText().trim();
        String sellingPriceStr = txtSellingPrice.getText().trim();
        String stockStr = txtStockQuantity.getText().trim();

        if (name.isEmpty() || buyingPriceStr.isEmpty() || sellingPriceStr.isEmpty() || stockStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all required fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int id = Integer.parseInt(txtProductId.getText().trim());
            String brand = txtBrand.getText().trim();
            String modelStr = txtModel.getText().trim();

            double buyingPrice = Double.parseDouble(buyingPriceStr);
            double sellingPrice = Double.parseDouble(sellingPriceStr);
            int stock = Integer.parseInt(stockStr);

            if (buyingPrice < 0 || sellingPrice < 0 || stock < 0) {
                JOptionPane.showMessageDialog(this, "Prices and stock quantity cannot be negative!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String selectedCategoryName = cmbCategory.getSelectedItem() != null ? cmbCategory.getSelectedItem().toString() : "";
            int categoryId = 1;
            List<Category> categories = categoryDAO.getAllCategories();
            for (Category cat : categories) {
                if (cat.getCategoryName().equalsIgnoreCase(selectedCategoryName)) {
                    categoryId = cat.getCategoryId();
                    break;
                }
            }

            Product product = new Product(id, categoryId, name, brand, modelStr, buyingPrice, sellingPrice, stock);
            boolean isUpdated = productDAO.updateProduct(product);

            if (isUpdated) {
                JOptionPane.showMessageDialog(this, "Product updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                clearFields();
                loadAllProducts();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update product!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values!", "Input Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txtProductId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a product from the table!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this product?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(txtProductId.getText());
                boolean isDeleted = productDAO.deleteProduct(id);

                if (isDeleted) {
                    JOptionPane.showMessageDialog(this, "Product deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    clearFields();
                    loadAllProducts();
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to delete product!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

