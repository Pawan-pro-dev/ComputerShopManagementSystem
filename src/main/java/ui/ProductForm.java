    private void tblProductMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductMouseClicked
        int selectedRow = tblProduct.getSelectedRow(); 
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) tblProduct.getModel();

            txtProductId.setText(model.getValueAt(selectedRow, 0) != null ? model.getValueAt(selectedRow, 0).toString() : "");

            int catId = Integer.parseInt(model.getValueAt(selectedRow, 1).toString());
            try {
                List<Category> categories = categoryDAO.getAllCategories();
                for (Category cat : categories) {
                    if (cat.getCategoryId() == catId) {
                        cmbCategory.setSelectedItem(cat.getCategoryName());
                        break;
                    }
                }
            } catch (Exception e) {
                e.printStackTrace();
            }

            txtProductName.setText(model.getValueAt(selectedRow, 2) != null ? model.getValueAt(selectedRow, 2).toString() : "");
            txtBrand.setText(model.getValueAt(selectedRow, 3) != null ? model.getValueAt(selectedRow, 3).toString() : "");
            txtModel.setText(model.getValueAt(selectedRow, 4) != null ? model.getValueAt(selectedRow, 4).toString() : "");
            txtBuyingPrice.setText(model.getValueAt(selectedRow, 5) != null ? model.getValueAt(selectedRow, 5).toString() : "");
            txtSellingPrice.setText(model.getValueAt(selectedRow, 6) != null ? model.getValueAt(selectedRow, 6).toString() : "");
            txtStockQuantity.setText(model.getValueAt(selectedRow, 7) != null ? model.getValueAt(selectedRow, 7).toString() : "");
        }
    }//GEN-LAST:event_tblProductMouseClicked

