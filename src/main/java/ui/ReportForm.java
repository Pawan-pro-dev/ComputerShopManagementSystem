    private void generateReportFromStream(String reportResourcePath, Map<String, Object> parameters, String reportTitle) {
    try {
        java.io.InputStream reportStream = getClass().getResourceAsStream(reportResourcePath);
        
        if (reportStream == null) {
            JOptionPane.showMessageDialog(this, "Report file not found: " + reportResourcePath, "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Connection conn = DBConnection.getConnection();
        JasperReport jasperReport = JasperCompileManager.compileReport(reportStream);
        JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, parameters, conn);

        if (jasperPrint.getPages().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No data available for this report!", "Info", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        JasperViewer viewer = new JasperViewer(jasperPrint, false);
        viewer.setTitle(reportTitle);
        viewer.setVisible(true);

    } catch (SQLException | JRException e) {
        JOptionPane.showMessageDialog(this, "Report Generation Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}

