    private void btnProductSalesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProductSalesActionPerformed
        String input = JOptionPane.showInputDialog(this, "Enter Product ID:", "Product Sales Report", JOptionPane.QUESTION_MESSAGE);
        if (input == null || input.trim().isEmpty()) return;

        try {
            int productId = Integer.parseInt(input.trim());
            java.util.Map<String, Object> parameters = new java.util.HashMap<>();
            parameters.put("PRODUCT_ID", productId);

            generateReportFromStream("/reports/product_sales_report.jrxml", parameters, "Product Sales Report");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid Product ID! Please enter a numeric value.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnProductSalesActionPerformed

