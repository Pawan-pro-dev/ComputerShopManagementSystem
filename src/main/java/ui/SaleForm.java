    private void loadCustomers() {
        try {
            cmbCustomer.removeAllItems();
            customerList = customerDAO.getAllCustomers();
            if (customerList != null) {
                for (Customer c : customerList) {
                    cmbCustomer.addItem(c.getName());
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading customers: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void loadProducts() {
        try {
            cmbProduct.removeAllItems();
            productList = productDAO.getAllProducts();
            if (productList != null) {
                for (Product p : productList) {
                    cmbProduct.addItem(p.getProductName());
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading products: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void calculateGrandTotal() {
        grandTotal = 0.0;
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            Object val = model.getValueAt(i, 4);
            if (val != null) {
                try {
                    grandTotal += Double.parseDouble(val.toString());
                } catch (NumberFormatException e) {
                    // Ignore invalid format
                }
            }
        }
        txtGrandTotal.setText(String.format("%.2f", grandTotal));
    }
    
    private void resetFormFields() {
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
        model.setRowCount(0);
        txtQty.setText("");
        txtUnitPrice.setText("");
        txtGrandTotal.setText("0.00");
        grandTotal = 0.0;
        if (cmbCustomer.getItemCount() > 0) cmbCustomer.setSelectedIndex(0);
        if (cmbProduct.getItemCount() > 0) cmbProduct.setSelectedIndex(0);
        if (cmbPaymentMethod.getItemCount() > 0) cmbPaymentMethod.setSelectedIndex(0);
        if (cmbPaymentStatus.getItemCount() > 0) cmbPaymentStatus.setSelectedIndex(0);
    }

