    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        if (cmbProduct.getSelectedItem() == null || productList == null) return;

        String qtyStr = txtQty.getText().trim();
        String priceStr = txtUnitPrice.getText().trim();

        if (qtyStr.isEmpty() || priceStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Quantity and Unit Price!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int qty = Integer.parseInt(qtyStr);
            double unitPrice = Double.parseDouble(priceStr);

            if (qty <= 0 || unitPrice <= 0) {
                JOptionPane.showMessageDialog(this, "Quantity and Unit Price must be greater than zero!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int selectedIndex = cmbProduct.getSelectedIndex();
            if (selectedIndex == -1 || selectedIndex >= productList.size()) return;

            Product selectedProduct = productList.get(selectedIndex);
            int productId = selectedProduct.getProductId();
            String selectedProductName = selectedProduct.getProductName();
            int currentAvailableStock = selectedProduct.getStockQuantity();

            DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
            
            int currentCartQty = 0;
            int existingRowIndex = -1;

            for (int i = 0; i < model.getRowCount(); i++) {
                int existingProdId = Integer.parseInt(model.getValueAt(i, 0).toString());
                if (existingProdId == productId) {
                    currentCartQty = Integer.parseInt(model.getValueAt(i, 3).toString());
                    existingRowIndex = i;
                    break;
                }
            }

            if ((currentCartQty + qty) > currentAvailableStock) {
                JOptionPane.showMessageDialog(this, 
                    "Insufficient Stock! Available Stock: " + currentAvailableStock + " (Already in Cart: " + currentCartQty + ")", 
                    "Stock Warning", JOptionPane.WARNING_MESSAGE);
                return;
            }

            if (existingRowIndex != -1) {
                int newQty = currentCartQty + qty;
                double newSubtotal = newQty * unitPrice;

                model.setValueAt(newQty, existingRowIndex, 3);
                model.setValueAt(newSubtotal, existingRowIndex, 4);
            } else {
                double subtotal = qty * unitPrice;
                model.addRow(new Object[]{
                    productId,
                    selectedProductName,
                    unitPrice,
                    qty,
                    subtotal
                });
            }

            calculateGrandTotal();
            txtQty.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for Quantity and Price!", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddToCartActionPerformed

    private void btnRemoveItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveItemActionPerformed
        int selectedRow = tblCart.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
            model.removeRow(selectedRow);
            calculateGrandTotal();
        } else {
            JOptionPane.showMessageDialog(this, "Please select an item from cart to remove!", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnRemoveItemActionPerformed

    private void btnSaveSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveSaleActionPerformed
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty! Please add items to cart before saving.", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (cmbCustomer.getSelectedItem() == null || customerList == null) {
            JOptionPane.showMessageDialog(this, "Please select a customer!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int selectedCustomerIndex = cmbCustomer.getSelectedIndex();
            if (selectedCustomerIndex == -1 || selectedCustomerIndex >= customerList.size()) return;

            int customerId = customerList.get(selectedCustomerIndex).getCustomerId();
            int userId = 1; 

            String paymentMethod = cmbPaymentMethod.getSelectedItem().toString();
            String paymentStatus = cmbPaymentStatus.getSelectedItem().toString();

            Sale sale = new Sale(customerId, userId, grandTotal, paymentMethod, paymentStatus);
            List<SaleItem> items = new ArrayList<>();

            for (int i = 0; i < model.getRowCount(); i++) {
                int pId = Integer.parseInt(model.getValueAt(i, 0).toString());
                double price = Double.parseDouble(model.getValueAt(i, 2).toString());
                int qty = Integer.parseInt(model.getValueAt(i, 3).toString());
                double subtotal = Double.parseDouble(model.getValueAt(i, 4).toString());

                SaleItem item = new SaleItem(pId, qty, price, subtotal);
                items.add(item);
            }

            boolean success = saleDAO.saveSaleTransaction(sale, items);

            if (success) {
                JOptionPane.showMessageDialog(this, "Sale completed successfully and stock updated!", "Success", JOptionPane.INFORMATION_MESSAGE);
                resetFormFields();
                loadProducts();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save sale transaction!", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "DB Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveSaleActionPerformed

